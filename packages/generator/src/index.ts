export function moduleDefinition(key: string): ModuleDefinition | undefined {
  const normalized = normalizeKey(key);
  return MODULES.find(
    (module) =>
      normalizeKey(module.key) === normalized ||
      normalizeKey(module.resourceType) === normalized ||
      module.aliases.some((alias) => normalizeKey(alias) === normalized),
  );
}

export function parseAuthoringText(text: string, source = '<inline>'): unknown {
  if (Buffer.byteLength(text, 'utf8') > MAX_SOURCE_BYTES) {
    throw new GeneratorInputError('Authoring input exceeds the 2 MiB parser safety limit.', [
      generatorFinding('EOM_GENERATOR_INPUT_TOO_LARGE', 'Authoring input is too large.', source),
    ]);
  }
  if (extname(source).toLowerCase() === '.json') {
    return parseStrictJson(text, source);
  }
  if (/(^|(?:\s|:|\[|,|-))(?:&|\*)[A-Za-z0-9_-]+/mu.test(text)) {
    throw new GeneratorInputError(
      'YAML anchors and aliases are not allowed in public authoring input.',
      [
        generatorFinding(
          'EOM_GENERATOR_YAML_ALIAS',
          'YAML anchors and aliases are disabled.',
          source,
        ),
      ],
    );
  }
  const document = parseDocument(text, {
    schema: 'core',
    strict: true,
    uniqueKeys: true,
    prettyErrors: true,
  });
  if (document.errors.length > 0) {
    throw new GeneratorInputError(
      'YAML parsing failed.',
      document.errors.map((error) =>
        generatorFinding('EOM_GENERATOR_YAML_SYNTAX', error.message, source),
      ),
    );
  }
  let value: unknown;
  try {
    value = document.toJS({ maxAliasCount: 0 }) as unknown;
  } catch (error) {
    throw new GeneratorInputError('YAML alias expansion is not allowed.', [
      generatorFinding(
        'EOM_GENERATOR_YAML_ALIAS',
        error instanceof Error ? error.message : 'YAML aliases are disabled.',
        source,
      ),
    ]);
  }
  assertJsonSafe(value, source, 0);
  return value;
}

export async function readAuthoringValue(
  file: string,
  maxBytes = MAX_SOURCE_BYTES,
): Promise<unknown> {
  return (await readAuthoringSnapshot(file, maxBytes)).value;
}

interface AuthoringSnapshot {
  readonly bytes: Buffer;
  readonly digest: string;
  readonly value: unknown;
}

async function readAuthoringSnapshot(file: string, maxBytes: number): Promise<AuthoringSnapshot> {
  const bytes = await readBoundedFile(file, maxBytes);
  const value = parseAuthoringBytes(bytes, file);
  return { bytes, digest: sha256Bytes(bytes), value };
}

function parseAuthoringBytes(bytes: Buffer, file: string): unknown {
  let text: string;
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  } catch (error) {
    if (error instanceof GeneratorInputError) throw error;
    throw new GeneratorInputError('Authoring input is not valid UTF-8.', [
      generatorFinding(
        'EOM_GENERATOR_UTF8_INVALID',
        error instanceof Error ? error.message : 'Authoring input is not valid UTF-8.',
        file,
      ),
    ]);
  }
  return parseAuthoringText(text, file);
}

export async function loadAuthoringConfig(configFile: string): Promise<EomConfig> {
  const absolute = resolve(configFile);
  return (await loadAuthoringConfigSnapshot(absolute)).config;
}

async function loadAuthoringConfigSnapshot(
  configFile: string,
): Promise<{ readonly config: EomConfig; readonly digest: string }> {
  const snapshot = await readAuthoringSnapshot(configFile, MAX_SOURCE_BYTES);
  const value = snapshot.value;
  const result = validateDocument(value, {
    schemaFile: 'config.schema.json',
    semantic: false,
  });
  if (!result.structuralValid) {
    throw new GeneratorInputError(
      'Authoring configuration does not match config.schema.json.',
      result.findings,
    );
  }
  if (!isJsonObject(value)) {
    throw new GeneratorInputError('Authoring configuration must be an object.');
  }
  return { config: value as unknown as EomConfig, digest: snapshot.digest };
}

export async function buildPublication(options: BuildOptions): Promise<BuildReport> {
  const configFile = resolve(options.configFile);
  const configSnapshot = await loadAuthoringConfigSnapshot(configFile);
  const loadedConfig = configSnapshot.config;
  const config: EomConfig =
    options.sign === true
      ? {
          ...loadedConfig,
          signing: { ...(loadedConfig.signing ?? {}), enabled: true },
        }
      : loadedConfig;
  const configDigest = configSnapshot.digest;
  const configDirectory = dirname(configFile);
  const outputRoot = resolve(options.outputRoot ?? resolve(configDirectory, config.output.root));
  const sourceRoot = resolve(configDirectory, config.source.root);
  const mode = inferBuildMode(options);
  const configuredFullOutput = resolve(configDirectory, config.output.root);
  const maxBytes = config.maxBytes ?? DEFAULT_OUTPUT_MAX_BYTES;
  const effectiveNow =
    options.now ??
    (options.deterministic === true || options.verifyDeterministic === true
      ? new Date(0)
      : new Date());
  let parsedSources: readonly ParsedSource[] = [];
  let inputs: readonly BuildInput[] = [];
  try {
    try {
      assertBuildSelectors(mode, options);
      assertApprovedSourcePath(sourceRoot);
      await assertSafeOutputRoot(outputRoot, configDirectory, sourceRoot, config, options, mode);
      if (mode !== 'full') {
        await assertPartialOutputTarget(
          outputRoot,
          configuredFullOutput,
          config,
          configDigest,
          mode,
          options,
        );
      }
    } catch (error) {
      if (error instanceof CandidatePolicyError) {
        throw new GeneratorInputError(error.message, [
          generatorFinding(
            'EOM_CANDIDATE_SOURCE_BLOCKED',
            'Candidate workspace paths cannot be used as publication generator inputs.',
            config.source.root,
          ),
        ]);
      }
      throw error;
    }
    parsedSources = await discoverSources(
      config,
      configFile,
      configDirectory,
      maxBytes,
      options.cacheDirectory,
      configDigest,
    );
    const selectedSources = selectBuildSources(
      parsedSources,
      mode,
      options.module,
      options.changedFiles,
      configDirectory,
    );
    inputs = selectedSources.map((source) => ({
      path: source.file,
      relativePath: source.relativePath,
      module: source.module.key,
      sha256: source.digest,
    }));
    const moduleBuild = buildModules(
      config,
      selectedSources,
      options.organization,
      mode === 'organization' || options.organization !== undefined,
    );
    let moduleDocuments: Record<string, JsonObject> = { ...moduleBuild.documents };
    let root = buildManifest(config, moduleDocuments, moduleBuild.organizationId);
    let signature:
      | {
          readonly enabled: true;
          readonly subject: string;
          readonly keyId: string;
          readonly valid: boolean;
        }
      | undefined;
    if (config.signing?.enabled === true) {
      const signed = await createSigningDocuments(
        config,
        configDirectory,
        sourceRoot,
        moduleDocuments,
        moduleBuild.organizationId,
        effectiveNow,
      );
      moduleDocuments = {
        ...moduleDocuments,
        'key-set': signed.keySet,
        signature: asJsonObject(signed.signature, 'signature'),
      };
      const keySetCanonical = stringValue(signed.keySet.canonical);
      if (!keySetCanonical) {
        throw new GeneratorInputError('The generated key set has no canonical URL.', [
          generatorFinding(
            'EOM_GENERATOR_SIGNING_KEY_SET',
            'The generated public key set must have a canonical HTTPS URL.',
          ),
        ]);
      }
      root = buildManifest(config, moduleDocuments, moduleBuild.organizationId, {
        keySet: keySetCanonical,
        signatures: [signed.signature.canonical],
        required: false,
        algorithm: 'EdDSA',
      });
      signature = {
        enabled: true,
        subject: signed.signature.subject,
        keyId: signed.signature.keyId,
        valid: true,
      };
    }
    const documents = { manifest: root, ...moduleDocuments };
    const findings = validateAndLint(documents, config, effectiveNow);
    const valid = isBuildValid(findings, config);
    const resources = Object.entries(moduleDocuments)
      .map(([type, document]) => ({
        type,
        canonical: stringValue(document.canonical) ?? '',
        path: 'public/eom/' + fileNameForResource(type),
        sha256: sha256Text(jsonText(document, config.output.prettyPrint !== false)),
        itemCount: itemCount(document),
        sourceFiles: moduleBuild.sourceMap[type] ?? [],
      }))
      .sort((left, right) => compareStrings(left.type, right.type));
    const sourceMap = Object.fromEntries(
      Object.entries(moduleBuild.sourceMap)
        .sort(([left], [right]) => compareStrings(left, right))
        .map(([key, values]) => [key, [...values].sort()]),
    );
    const partial = createModeReport(mode, options, selectedSources, valid);
    const baseReport: BuildReport = {
      toolVersion: '1.0.0-rc.3',
      specification: SPECIFICATION,
      configDigest,
      valid,
      written: false,
      dryRun: options.dryRun === true,
      outputRoot,
      inputs,
      resources,
      findings,
      sourceMap,
      overlays: moduleBuild.overlays,
      privacy: privacyReport(config, findings),
      conflicts: conflictIds(findings),
      mode,
      ...(signature ? { signature } : {}),
      partial,
    };
    if (!valid || options.dryRun === true) {
      return baseReport;
    }
    const deterministic =
      options.verifyDeterministic === true
        ? await verifyDeterministicBuild(configFile, options, effectiveNow)
        : undefined;
    if (deterministic && !deterministic.valid) {
      return {
        ...baseReport,
        valid: false,
        deterministic,
        partial: {
          ...baseReport.partial,
          destinationKind: 'report-only',
          outputKind: 'report-only',
          completePublication: false,
        },
      };
    }
    const fingerprint = await writePublication(
      outputRoot,
      root,
      moduleDocuments,
      config,
      baseReport,
      config.output.prettyPrint !== false,
      mode,
    );
    return {
      ...baseReport,
      written: true,
      fingerprint,
      ...(deterministic ? { deterministic } : {}),
    };
  } catch (error) {
    if (!(error instanceof GeneratorInputError)) throw error;
    return {
      toolVersion: '1.0.0-rc.3',
      specification: SPECIFICATION,
      configDigest,
      valid: false,
      written: false,
      dryRun: options.dryRun === true,
      outputRoot,
      inputs,
      resources: [],
      findings:
        error.findings.length > 0
          ? error.findings
          : [generatorFinding('EOM_GENERATOR_INPUT_INVALID', error.message)],
      sourceMap: {},
      overlays: [],
      privacy: privacyReport(config, error.findings),
      conflicts: conflictIds(error.findings),
      mode,
      partial: {
        mode,
        ...(options.module ? { module: options.module } : {}),
        ...(options.organization ? { organization: options.organization } : {}),
        ...(options.changedFiles ? { changedFiles: options.changedFiles } : {}),
        selectedModules: [],
        selectedInputs: [],
        dependencyClosure: [],
        omittedModules: MODULES.filter((item) => item.key !== 'organization').map(
          (item) => item.key,
        ),
        omittedResources: MODULES.filter((item) => item.key !== 'organization').map(
          (item) => item.resourceType,
        ),
        destinationKind: 'report-only',
        outputKind: 'report-only',
        completePublication: false,
      },
    };
  }
}

async function verifyDeterministicBuild(
  configFile: string,
  options: BuildOptions,
  now: Date,
): Promise<NonNullable<BuildReport['deterministic']>> {
  const temporaryRoot = await mkdtemp(join(tmpdir(), 'eom-build-repro-'));
  const firstOutput = join(temporaryRoot, 'first', 'public');
  const secondOutput = join(temporaryRoot, 'second', 'public');
  try {
    const buildOptions = (outputRoot: string): BuildOptions => ({
      configFile,
      outputRoot,
      now,
      deterministic: true,
      verifyDeterministic: false,
      allowExternalOutput: true,
      ...(options.sign ? { sign: true } : {}),
      ...(options.module ? { module: options.module } : {}),
      ...(options.organization ? { organization: options.organization } : {}),
      ...(options.mode ? { mode: options.mode } : {}),
      ...(options.changedFiles ? { changedFiles: options.changedFiles } : {}),
    });
    const [first, second] = await Promise.all([
      buildPublication(buildOptions(firstOutput)),
      buildPublication(buildOptions(secondOutput)),
    ]);
    if (!first.valid || !second.valid || !first.written || !second.written) {
      return {
        checked: true,
        valid: false,
        differences: ['isolated deterministic builds did not both complete successfully'],
      };
    }
    const firstFiles = await filesWithBytes(firstOutput);
    const secondFiles = await filesWithBytes(secondOutput);
    const names = [...new Set([...firstFiles.keys(), ...secondFiles.keys()])].sort();
    const differences = names.filter((name) => {
      const left = firstFiles.get(name);
      const right = secondFiles.get(name);
      return left === undefined || right === undefined || !left.equals(right);
    });
    return { checked: true, valid: differences.length === 0, differences };
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }
}

async function filesWithBytes(directory: string): Promise<Map<string, Buffer>> {
  const result = new Map<string, Buffer>();
  for (const file of await walkFiles(directory)) {
    result.set(relative(directory, file).replaceAll('\\', '/'), await readFile(file));
  }
  return result;
}

function createModeReport(
  mode: BuildMode,
  options: BuildOptions,
  selectedSources: readonly ParsedSource[],
  valid: boolean,
): PartialBuildReport {
  const selectedModules = [...new Set(selectedSources.map((source) => source.module.key))].sort(
    compareStrings,
  );
  const omittedModules = MODULES.filter((module) => !selectedModules.includes(module.key)).map(
    (module) => module.key,
  );
  const changedFiles = options.changedFiles?.slice().sort(compareStrings);
  const selectedInputs = selectedSources.map((source) => source.relativePath).sort(compareStrings);
  const omittedResources = MODULES.filter((module) => !selectedModules.includes(module.key)).map(
    (module) => module.resourceType,
  );
  return {
    mode,
    ...(options.module ? { module: options.module } : {}),
    ...(options.organization ? { organization: options.organization } : {}),
    ...(changedFiles ? { changedFiles } : {}),
    selectedInputs,
    selectedModules,
    dependencyClosure: selectedModules,
    omittedModules,
    omittedResources,
    destinationKind:
      !valid || options.dryRun === true
        ? 'report-only'
        : mode === 'full'
          ? 'full-publication'
          : 'partial-output',
    outputKind:
      !valid || options.dryRun === true
        ? 'report-only'
        : mode === 'full' || mode === 'organization'
          ? 'complete-publication'
          : 'partial-bundle',
    completePublication:
      valid && options.dryRun !== true && (mode === 'full' || mode === 'organization'),
  };
}

function inferBuildMode(options: BuildOptions): BuildMode {
  if (options.mode !== undefined) return options.mode;
  if (options.changedFiles !== undefined && options.changedFiles.length > 0) {
    return 'changed-files';
  }
  if (options.module !== undefined) return 'module';
  if (options.organization !== undefined) return 'organization';
  return 'full';
}

function assertBuildSelectors(mode: BuildMode, options: BuildOptions): void {
  if (mode === 'full' && (options.module || options.organization || options.changedFiles?.length)) {
    throw new GeneratorInputError('The full build mode cannot include partial-build selectors.', [
      generatorFinding(
        'EOM_GENERATOR_BUILD_MODE_CONFLICT',
        'Choose full mode or an explicit module, organization, or changed-files selector.',
      ),
    ]);
  }
  if (mode === 'module' && !options.module) {
    throw new GeneratorInputError('Module build mode requires a module selector.', [
      generatorFinding('EOM_GENERATOR_MODULE_REQUIRED', 'Pass --module with module build mode.'),
    ]);
  }
  if (mode === 'organization' && (!options.organization || options.changedFiles?.length)) {
    throw new GeneratorInputError(
      'Organization build mode requires only an organization selector.',
      [
        generatorFinding(
          'EOM_GENERATOR_ORGANIZATION_REQUIRED',
          'Pass --organization with organization build mode.',
        ),
      ],
    );
  }
  if (mode === 'changed-files' && !options.changedFiles?.length) {
    throw new GeneratorInputError('Changed-files build mode requires at least one source path.', [
      generatorFinding(
        'EOM_GENERATOR_CHANGED_FILES_REQUIRED',
        'Pass one or more --changed source paths.',
      ),
    ]);
  }
  if (mode !== 'module' && options.module) {
    throw new GeneratorInputError('A module selector requires module build mode.', [
      generatorFinding('EOM_GENERATOR_BUILD_MODE_CONFLICT', 'Use mode module for --module.'),
    ]);
  }
  if (mode !== 'organization' && mode !== 'module' && options.organization) {
    throw new GeneratorInputError(
      'An organization selector requires organization or module mode.',
      [
        generatorFinding(
          'EOM_GENERATOR_BUILD_MODE_CONFLICT',
          'Use organization mode or combine --organization with module mode.',
        ),
      ],
    );
  }
  if (mode !== 'changed-files' && options.changedFiles?.length) {
    throw new GeneratorInputError('Changed source paths require changed-files build mode.', [
      generatorFinding(
        'EOM_GENERATOR_BUILD_MODE_CONFLICT',
        'Use mode changed-files for --changed.',
      ),
    ]);
  }
}

function selectBuildSources(
  sources: readonly ParsedSource[],
  mode: BuildMode,
  selectedModule: string | undefined,
  changedFiles: readonly string[] | undefined,
  configDirectory: string,
): readonly ParsedSource[] {
  if (mode === 'full' || mode === 'organization') return sources;
  const selectedKeys = new Set<string>();
  if (mode === 'module') {
    const module = selectedModule === undefined ? undefined : moduleDefinition(selectedModule);
    if (!module) {
      throw new GeneratorInputError('Unknown build module ' + (selectedModule ?? '') + '.', [
        generatorFinding(
          'EOM_GENERATOR_UNKNOWN_MODULE',
          'The selected build module is not registered.',
          selectedModule,
        ),
      ]);
    }
    addModuleDependencies(module.key, selectedKeys);
  } else {
    const requested = new Set(
      (changedFiles ?? []).map((file) => resolve(configDirectory, file).toLowerCase()),
    );
    const changedSources = sources.filter((source) => requested.has(source.file.toLowerCase()));
    if (changedSources.length === 0) {
      throw new GeneratorInputError('No changed source paths were discovered.', [
        generatorFinding(
          'EOM_GENERATOR_CHANGED_FILE_NOT_FOUND',
          'Each changed-files selector must identify a configured source, import, include, or overlay file.',
          changedFiles?.join(', '),
        ),
      ]);
    }
    for (const source of changedSources) addModuleDependencies(source.module.key, selectedKeys);
  }
  const filtered = sources.filter(
    (source) => source.module.key === 'organization' || selectedKeys.has(source.module.key),
  );
  if (!filtered.some((source) => selectedKeys.has(source.module.key))) {
    throw new GeneratorInputError('The selected build has no discovered module source files.', [
      generatorFinding(
        'EOM_GENERATOR_MODULE_NOT_FOUND',
        'Add a source file for the selected module or choose another selector.',
      ),
    ]);
  }
  return filtered;
}

function addModuleDependencies(moduleKey: string, selected: Set<string>): void {
  if (selected.has(moduleKey)) return;
  selected.add(moduleKey);
  for (const dependency of MODULE_DEPENDENCIES[moduleKey] ?? []) {
    addModuleDependencies(dependency, selected);
  }
}

async function discoverSources(
  config: EomConfig,
  configFile: string,
  configDirectory: string,
  maxBytes: number,
  cacheDirectory: string | undefined,
  configDigest: string,
): Promise<readonly ParsedSource[]> {
  const sourceRoot = resolve(configDirectory, config.source.root);
  const parsed: ParsedSource[] = [];
  const claimedFiles = new Map<string, string>();
  const discoverySpecs: Array<{
    readonly configuredKey: string;
    readonly patterns: readonly string[];
    readonly kind: ParsedSource['kind'];
    readonly overlay?: EomSourceOverlayConfig;
  }> = [];
  for (const [configuredKey, patterns] of Object.entries(config.source.modules)) {
    discoverySpecs.push({ configuredKey, patterns, kind: 'source' });
  }
  for (const entry of [...(config.source.imports ?? []), ...(config.source.includes ?? [])]) {
    discoverySpecs.push({ configuredKey: entry.module, patterns: entry.patterns, kind: 'import' });
  }
  for (const overlay of [...(config.source.overlays ?? [])].sort(
    (left, right) => left.priority - right.priority || compareStrings(left.name, right.name),
  )) {
    for (const [configuredKey, patterns] of Object.entries(overlay.modules)) {
      discoverySpecs.push({ configuredKey, patterns, kind: 'overlay', overlay });
    }
  }

  for (const { configuredKey, patterns, kind, overlay } of discoverySpecs) {
    const module = moduleDefinition(configuredKey);
    if (!module) {
      throw new GeneratorInputError('Unknown source module ' + configuredKey + '.', [
        generatorFinding(
          'EOM_GENERATOR_UNKNOWN_MODULE',
          'The source module is not registered.',
          configuredKey,
        ),
      ]);
    }
    for (const pattern of patterns) {
      const files = await matchingFiles(sourceRoot, pattern);
      for (const file of files) {
        const normalized = resolve(file);
        if (normalized === resolve(configFile)) continue;
        if (kind !== 'overlay') {
          const previous = claimedFiles.get(normalized);
          if (previous && previous !== module.key) {
            throw new GeneratorInputError('Source file is assigned to multiple modules.', [
              generatorFinding(
                'EOM_GENERATOR_SOURCE_MULTI_ASSIGNMENT',
                'A source file may belong to one module only.',
                normalized,
                [previous, module.key],
              ),
            ]);
          }
          if (previous) continue;
          claimedFiles.set(normalized, module.key);
        }
        const snapshot = await readAuthoringSnapshot(normalized, maxBytes);
        const digest = snapshot.digest;
        const value = await readCachedAuthoringValue(
          normalized,
          digest,
          maxBytes,
          cacheDirectory,
          configDigest,
          snapshot.value,
        );
        parsed.push({
          module,
          file: normalized,
          relativePath: normalizePath(relative(configDirectory, normalized)),
          value,
          digest,
          kind,
          ...(overlay ? { overlay } : {}),
        });
      }
    }
  }
  if (parsed.length === 0) {
    throw new GeneratorInputError('No source files were discovered.', [
      generatorFinding(
        'EOM_GENERATOR_NO_SOURCES',
        'The configuration did not discover any source files.',
      ),
    ]);
  }
  return parsed.sort((left, right) => {
    const moduleOrder = compareStrings(left.module.key, right.module.key);
    if (moduleOrder !== 0) return moduleOrder;
    const kindOrder = compareStrings(left.kind, right.kind);
    return kindOrder !== 0 ? kindOrder : compareStrings(left.relativePath, right.relativePath);
  });
}

async function readCachedAuthoringValue(
  file: string,
  sourceDigest: string,
  maxBytes: number,
  cacheDirectory: string | undefined,
  configDigest: string,
  sourceValue: unknown,
): Promise<unknown> {
  if (!cacheDirectory) return sourceValue;
  const cacheKey = createHash('sha256')
    .update(`1.0.0-rc.3\0${SPECIFICATION}\0${configDigest}\0${sourceDigest}`)
    .digest('hex');
  const directory = resolve(cacheDirectory);
  const cachePath = join(directory, `.eom-source-${cacheKey}.json`);
  try {
    const cacheStat = await stat(cachePath);
    const maxCacheBytes = Math.min(16 * 1024 * 1024, Math.max(maxBytes * 4, 1024 * 1024));
    if (cacheStat.size > maxCacheBytes) throw new Error('The source cache entry is too large.');
    const cached = parseStrictJson(
      new TextDecoder('utf-8', { fatal: true }).decode(
        await readBoundedFile(cachePath, maxCacheBytes),
      ),
      cachePath,
    );
    if (
      isJsonObject(cached) &&
      cached.cacheVersion === '1' &&
      cached.sourceDigest === sourceDigest &&
      cached.configDigest === configDigest &&
      Object.hasOwn(cached, 'value') &&
      Buffer.byteLength(JSON.stringify(cached.value) ?? '', 'utf8') <= maxCacheBytes
    ) {
      assertJsonSafe(cached.value, cachePath, 0);
      return cached.value;
    }
  } catch {
    // A cache miss or malformed cache entry falls back to authoritative source bytes.
  }

  const value = sourceValue;
  try {
    await mkdir(directory, { recursive: true });
    const temporary = `${cachePath}.${process.pid}.tmp`;
    await writeFile(
      temporary,
      stringifyCanonical({
        cacheVersion: '1',
        sourceDigest,
        configDigest,
        value: value as JsonValue,
      }),
      'utf8',
    );
    await rename(temporary, cachePath);
    const entries = (await readdir(directory, { withFileTypes: true }))
      .filter((entry) => entry.isFile() && entry.name.startsWith('.eom-source-'))
      .map((entry) => join(directory, entry.name));
    if (entries.length > 256) {
      const dated = await Promise.all(
        entries.map(async (entry) => ({ entry, modified: (await stat(entry)).mtimeMs })),
      );
      dated.sort((left, right) => left.modified - right.modified);
      await Promise.all(
        dated.slice(0, entries.length - 256).map((entry) => rm(entry.entry, { force: true })),
      );
    }
  } catch {
    // Source parsing remains authoritative when an optional cache cannot be written.
  }
  return value;
}

async function readBoundedFile(file: string, maxBytes: number): Promise<Buffer> {
  const handle = await open(file, 'r');
  try {
    const information = await handle.stat();
    if (!information.isFile()) {
      throw new GeneratorInputError('Authoring input must be a regular file.', [
        generatorFinding(
          'EOM_GENERATOR_INPUT_INVALID',
          'Authoring input must be a regular file.',
          file,
        ),
      ]);
    }
    if (information.size > maxBytes) {
      throw new GeneratorInputError('Authoring input exceeds its configured size limit.', [
        generatorFinding('EOM_GENERATOR_INPUT_TOO_LARGE', 'Authoring input is too large.', file),
      ]);
    }
    const chunks: Buffer[] = [];
    let total = 0;
    for (;;) {
      const chunk = Buffer.allocUnsafe(Math.min(64 * 1024, maxBytes - total + 1));
      const { bytesRead } = await handle.read(chunk, 0, chunk.length, null);
      if (bytesRead === 0) break;
      total += bytesRead;
      chunks.push(chunk.subarray(0, bytesRead));
      if (total > maxBytes) {
        throw new GeneratorInputError('Authoring input exceeds its configured size limit.', [
          generatorFinding('EOM_GENERATOR_INPUT_TOO_LARGE', 'Authoring input is too large.', file),
        ]);
      }
    }
    return Buffer.concat(chunks, total);
  } finally {
    await handle.close();
  }
}

async function assertSafeOutputRoot(
  outputRoot: string,
  configDirectory: string,
  sourceRoot: string,
  config: EomConfig,
  options: BuildOptions,
  mode: BuildMode,
): Promise<void> {
  await assertNoSymlinkEscape(outputRoot);
  const configRealDirectory = await realpath(configDirectory);
  const resolvedSourceRoot = await realpath(sourceRoot);
  const projectRoot = await realpath(
    sourceRoot === configDirectory ? dirname(configRealDirectory) : configRealDirectory,
  );
  const outputParent = await existingRealPath(dirname(outputRoot));
  const outputCandidate = join(outputParent, relative(dirname(outputRoot), outputRoot));
  const outputRealPath = await existingRealPath(outputCandidate);
  const buildCandidate = buildDirectoryForOutput(outputCandidate, mode);
  await assertNoSymlinkEscape(buildCandidate);
  const buildRealPath = await existingRealPath(buildCandidate);
  const home = await existingRealPath(homedir());
  const cwd = await existingRealPath(process.cwd());

  if (outputRealPath === buildRealPath) {
    throw unsafeOutputError(
      outputRoot,
      'The publication output and protected build-report directory must be distinct.',
    );
  }

  if (
    parse(outputRealPath).root === outputRealPath ||
    outputRealPath === home ||
    outputRealPath === cwd
  ) {
    throw unsafeOutputError(outputRoot, 'The output directory is a protected filesystem root.');
  }
  if (
    outputRealPath === projectRoot ||
    outputRealPath === configRealDirectory ||
    outputRealPath === resolvedSourceRoot ||
    isWithin(resolvedSourceRoot, outputRealPath) ||
    isWithin(outputRealPath, resolvedSourceRoot) ||
    isWithin(outputRealPath, configRealDirectory)
  ) {
    throw unsafeOutputError(
      outputRoot,
      'The output directory must not replace, contain, or sit inside the authoring project inputs.',
    );
  }
  if (resolvedSourceRoot !== configRealDirectory && !isWithin(projectRoot, resolvedSourceRoot)) {
    throw unsafeOutputError(
      sourceRoot,
      'The source directory must be a real descendant of the authoring project; symlink escapes are not allowed.',
    );
  }
  if (buildRealPath === resolvedSourceRoot || isWithin(resolvedSourceRoot, buildRealPath)) {
    throw unsafeOutputError(
      buildCandidate,
      'The build-report directory must not sit inside the source root.',
    );
  }
  if (options.allowExternalOutput !== true && !isWithin(projectRoot, outputRealPath)) {
    throw unsafeOutputError(
      outputRoot,
      'The output directory must be inside the authoring project unless external output is explicitly enabled.',
    );
  }
  if (options.allowExternalOutput !== true && !isWithin(projectRoot, buildRealPath)) {
    throw unsafeOutputError(
      buildCandidate,
      'The build-report directory must be inside the authoring project unless external output is explicitly enabled.',
    );
  }

  const expectedMarker = {
    buildMode: mode,
    projectIdentity: projectIdentity(config),
    selector: selectorFor(mode, options),
  };
  await assertReplaceableDirectory(outputCandidate, outputRoot, expectedMarker);
  await assertReplaceableDirectory(buildCandidate, buildCandidate, expectedMarker);
}

async function assertPartialOutputTarget(
  outputRoot: string,
  configuredFullOutput: string,
  config: EomConfig,
  configDigest: string,
  mode: Exclude<BuildMode, 'full'>,
  options: BuildOptions,
): Promise<void> {
  if ((await existingRealPath(outputRoot)) === (await existingRealPath(configuredFullOutput))) {
    throw unsafeOutputError(
      outputRoot,
      'Partial builds require an explicit output distinct from the configured full publication root.',
    );
  }
  let information;
  try {
    information = await stat(outputRoot);
  } catch (error) {
    if (isNotFound(error)) return;
    throw error;
  }
  if (!information.isDirectory()) {
    throw unsafeOutputError(outputRoot, 'The partial-build output target must be a directory.');
  }
  let marker: JsonValue;
  try {
    marker = parseStrictJson(
      await readFile(join(outputRoot, GENERATED_MARKER), 'utf8'),
      outputRoot,
    );
  } catch {
    throw unsafeOutputError(
      outputRoot,
      'A partial build may replace only an existing compatible generator-owned partial bundle.',
    );
  }
  if (
    !isJsonObject(marker) ||
    marker.generator !== 'eom' ||
    marker.specification !== SPECIFICATION ||
    marker.ownershipVersion !== GENERATED_OWNERSHIP_VERSION ||
    marker.buildMode !== mode ||
    marker.configDigest !== configDigest ||
    marker.publisherOrigin !== config.publisher.origin ||
    marker.projectIdentity !== projectIdentity(config) ||
    !isJsonObject(marker.selector) ||
    stringifyCanonical(marker.selector) !== stringifyCanonical(selectorFor(mode, options))
  ) {
    throw unsafeOutputError(
      outputRoot,
      'A partial build cannot replace a full publication or a partial bundle from another project or mode.',
    );
  }
}

function buildDirectoryForOutput(outputRoot: string, mode: BuildMode): string {
  return mode === 'full'
    ? join(dirname(outputRoot), 'build')
    : join(dirname(outputRoot), `.eom-build-${basename(outputRoot)}`);
}

function projectIdentity(config: EomConfig): string {
  return `${config.publisher.origin}|${config.project.name}|${config.project.protocolVersion}`;
}

function generatedMarker(
  config: EomConfig,
  report: BuildReport,
  mode: BuildMode,
  publisherOrigin: string | undefined,
  root: JsonObject,
): JsonObject {
  const organizations = Array.isArray(root.organizations) ? root.organizations : [];
  const firstOrganization = organizations.find(isJsonObject);
  const organization =
    report.partial?.organization ??
    stringValue(firstOrganization?.id) ??
    config.publisher.organizationId;
  const selector = selectorForReport(report, mode);
  return asJsonObject(
    {
      generator: 'eom',
      ownershipVersion: GENERATED_OWNERSHIP_VERSION,
      specification: report.specification,
      toolVersion: report.toolVersion,
      buildMode: mode,
      projectIdentity: projectIdentity(config),
      configDigest: report.configDigest,
      ...(publisherOrigin ? { publisherOrigin } : {}),
      ...(organization ? { organization } : {}),
      selector,
    },
    'generated ownership marker',
  );
}

