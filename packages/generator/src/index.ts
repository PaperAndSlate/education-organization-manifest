async function assertReplaceableDirectory(
  directory: string,
  displayPath: string,
  expected?: ReplacementMarkerExpectation,
): Promise<void> {
  let information;
  try {
    information = await stat(directory);
  } catch (error) {
    if (isNotFound(error)) return;
    throw error;
  }
  if (!information.isDirectory()) {
    throw unsafeOutputError(displayPath, 'The output target must be a directory.');
  }

  const markerPath = join(directory, GENERATED_MARKER);
  let markerText: string;
  try {
    markerText = await readFile(markerPath, 'utf8');
  } catch (error) {
    if (isNotFound(error)) {
      throw unsafeOutputError(
        displayPath,
        `Refusing to replace an existing unmarked directory. Add ${GENERATED_MARKER} with the generator marker fields.`,
      );
    }
    throw error;
  }
  let marker: JsonValue;
  try {
    marker = parseStrictJson(markerText, markerPath);
  } catch {
    throw unsafeOutputError(displayPath, `The ${GENERATED_MARKER} file is not valid strict JSON.`);
  }
  if (
    !isJsonObject(marker) ||
    marker.generator !== 'eom' ||
    marker.specification !== SPECIFICATION ||
    typeof marker.toolVersion !== 'string' ||
    marker.ownershipVersion !== GENERATED_OWNERSHIP_VERSION ||
    typeof marker.projectIdentity !== 'string' ||
    (expected !== undefined &&
      (marker.projectIdentity !== expected.projectIdentity ||
        marker.buildMode !== expected.buildMode ||
        !isJsonObject(marker.selector) ||
        stringifyCanonical(marker.selector) !== stringifyCanonical(expected.selector)))
  ) {
    throw unsafeOutputError(
      displayPath,
      `The ${GENERATED_MARKER} file is not a valid EOM generator-owned marker.`,
    );
  }
}

function selectorFor(mode: BuildMode, options: BuildOptions): JsonObject {
  if (mode === 'full') return {};
  const selector: Record<string, unknown> = {};
  if (options.module !== undefined) selector.module = options.module;
  if (options.organization !== undefined) selector.organization = options.organization;
  if (options.changedFiles !== undefined) {
    selector.changedFiles = [...options.changedFiles].sort(compareStrings);
  }
  return asJsonObject(selector, 'build selector');
}

function selectorForReport(report: BuildReport, mode: BuildMode): JsonObject {
  if (mode === 'full' || report.partial === undefined) return {};
  const selector: Record<string, unknown> = {};
  if (report.partial.module !== undefined) selector.module = report.partial.module;
  if (report.partial.organization !== undefined)
    selector.organization = report.partial.organization;
  if (report.partial.changedFiles !== undefined) {
    selector.changedFiles = [...report.partial.changedFiles].sort(compareStrings);
  }
  return asJsonObject(selector, 'build selector');
}

async function existingRealPath(path: string): Promise<string> {
  try {
    return await realpath(path);
  } catch (error) {
    if (!isNotFound(error)) throw error;
    const parent = dirname(path);
    if (parent === path) return resolve(path);
    return join(await existingRealPath(parent), path.slice(parent.length + 1));
  }
}

function isWithin(parent: string, child: string): boolean {
  const value = relative(parent, child);
  return value === '' || (value !== '..' && !value.startsWith(`..${sep}`) && !isAbsolute(value));
}

function unsafeOutputError(path: string, message: string): GeneratorInputError {
  return new GeneratorInputError(message, [
    generatorFinding('EOM_GENERATOR_OUTPUT_UNSAFE', message, path),
  ]);
}

async function assertNoSymlinkEscape(path: string): Promise<void> {
  const lexicalPath = resolve(path);
  const realPath = await existingRealPath(lexicalPath);
  if (normalizeFsPath(realPath) !== normalizeFsPath(lexicalPath)) {
    throw unsafeOutputError(
      path,
      'Generator output paths must not traverse symbolic links or junctions.',
    );
  }
  try {
    const information = await lstat(lexicalPath);
    if (information.isSymbolicLink()) {
      throw unsafeOutputError(
        path,
        'Generator output paths must not be symbolic links or junctions.',
      );
    }
  } catch (error) {
    if (error instanceof GeneratorInputError || !isNotFound(error)) throw error;
  }
}

function normalizeFsPath(value: string): string {
  return resolve(value).replaceAll('/', '\\').toLowerCase();
}

async function matchingFiles(root: string, pattern: string): Promise<readonly string[]> {
  const normalizedPattern = normalizePath(pattern).replace(/^\.\//u, '');
  const allFiles = await walkFiles(root);
  const matcher = globRegExp(normalizedPattern);
  return allFiles
    .filter((file) => matcher.test(normalizePath(relative(root, file))))
    .sort((left, right) =>
      compareStrings(normalizePath(relative(root, left)), normalizePath(relative(root, right))),
    );
}

async function walkFiles(directory: string): Promise<readonly string[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walkFiles(path)));
    } else if (entry.isFile()) {
      files.push(path);
    }
  }
  return files;
}

function globRegExp(pattern: string): RegExp {
  let expression = '^';
  for (let index = 0; index < pattern.length; index += 1) {
    const character = pattern[index] ?? '';
    if (character === '*' && pattern[index + 1] === '*') {
      index += 1;
      if (pattern[index + 1] === '/') {
        index += 1;
        expression += '(?:.*/)?';
      } else {
        expression += '.*';
      }
    } else if (character === '*') {
      expression += '[^/]*';
    } else if (character === '?') {
      expression += '[^/]';
    } else {
      expression += escapeRegExp(character);
    }
  }
  return new RegExp(expression + '$', 'u');
}

function buildModules(
  config: EomConfig,
  sources: readonly ParsedSource[],
  requestedOrganization?: string,
  filterOrganization = false,
): ModuleBuild {
  const groups = new Map<string, ParsedSource[]>();
  for (const source of sources) {
    const group = groups.get(source.module.key) ?? [];
    group.push(source);
    groups.set(source.module.key, group);
  }
  const overlays: AppliedOverlay[] = [];
  const organizationSources = (groups.get('organization') ?? []).filter(
    (source) => source.kind !== 'overlay',
  );
  if (organizationSources.length === 0) {
    throw new GeneratorInputError('An organization source is required.', [
      generatorFinding('EOM_GENERATOR_ORGANIZATION_REQUIRED', 'Add source.modules.organization.'),
    ]);
  }
  const organizationCandidates = organizationSources.flatMap((source) =>
    extractItems(source.value, MODULES[0]!).map((value) => ({ source, value })),
  );
  const requestedId = requestedOrganization ?? config.publisher.organizationId;
  let selectedOrganization = organizationCandidates[0];
  if (requestedId) {
    const matches = organizationCandidates.filter(
      ({ value }) => stringValue(value.id) === requestedId,
    );
    if (matches.length === 0) {
      throw new GeneratorInputError(
        'The requested organization was not found in the selected source.',
        [
          generatorFinding(
            'EOM_GENERATOR_ORGANIZATION_NOT_FOUND',
            'The requested organization identifier is not present in the authoring source.',
            requestedId,
          ),
        ],
      );
    }
    if (matches.length > 1) {
      throw duplicateOrganizationError(
        requestedId,
        matches.map(({ source }) => source.file),
      );
    }
    selectedOrganization = matches[0];
  } else if (organizationCandidates.length !== 1) {
    throw new GeneratorInputError(
      'A multi-organization authoring source requires an organization selector.',
      [
        generatorFinding(
          'EOM_GENERATOR_ORGANIZATION_REQUIRED',
          'Set publisher.organizationId or pass --organization when more than one organization is authored.',
          'source.modules.organization',
          organizationCandidates.map(({ source }) => source.file),
        ),
      ],
    );
  }
  const organizationValue = selectedOrganization?.value;
  if (!organizationValue) {
    throw new GeneratorInputError('An organization source is required.', [
      generatorFinding('EOM_GENERATOR_ORGANIZATION_REQUIRED', 'Add source.modules.organization.'),
    ]);
  }
  const selectedOrganizationId = stringValue(organizationValue.id);
  let organization = normalizeOrganization(organizationValue, config);
  for (const source of sortedOverlaySources(groups.get('organization') ?? [])) {
    if (source.kind !== 'overlay' || !source.overlay) continue;
    const items = extractItems(source.value, MODULES[0]!);
    for (const item of items) {
      if (selectedOrganizationId !== undefined && stringValue(item.id) !== selectedOrganizationId) {
        continue;
      }
      organization = normalizeOrganization(
        applyOverlayFields(organization, item, source.overlay, source.file, 'organization'),
        config,
      );
      overlays.push({
        name: source.overlay.name,
        owner: source.overlay.owner,
        priority: source.overlay.priority,
        module: 'organization',
        sourceFiles: [source.relativePath],
      });
    }
  }
  const organizationId = stringValue(organization.id);
  if (!organizationId) {
    throw new GeneratorInputError('The organization source must have an id.', [
      generatorFinding('EOM_GENERATOR_ID_REQUIRED', 'The organization source has no stable id.'),
    ]);
  }
  const documents: Record<string, JsonObject> = {
    'organization-profile': organization,
  };
  const sourceMap: Record<string, readonly string[]> = {
    'organization-profile': organizationSources.map((source) => source.relativePath),
  };
  const organizationOverlayFiles = (groups.get('organization') ?? [])
    .filter((source) => source.kind === 'overlay')
    .map((source) => source.relativePath);
  if (organizationOverlayFiles.length > 0) {
    sourceMap['organization-profile'] = [
      ...(sourceMap['organization-profile'] ?? []),
      ...organizationOverlayFiles,
    ].sort();
  }
  const contacts = (groups.get('contacts') ?? []).filter((source) => source.kind !== 'overlay');
  const contactOverlaySources = sortedOverlaySources(groups.get('contacts') ?? []);
  if (contacts.length === 0 && contactOverlaySources.length > 0) {
    throw overlayTargetError(contactOverlaySources[0]!.file, 'contacts', undefined);
  }
  if (contacts.length > 0) {
    let contactDocument = buildContactDocument(contacts, organizationId, config);
    let contactItems = Array.isArray(contactDocument.contacts)
      ? contactDocument.contacts.filter(isJsonObject)
      : [];
    if (filterOrganization) {
      contactItems = contactItems
        .filter((item) => itemBelongsToOrganization(item, organizationId))
        .map((item) => filterOrganizationReferences(item, organizationId));
    }
    for (const source of contactOverlaySources) {
      if (!source.overlay) continue;
      for (const item of extractItems(source.value, {
        key: 'contacts',
        aliases: [],
        resourceType: 'contact-directory',
        fileName: 'contacts.json',
      })) {
        if (filterOrganization && !itemBelongsToOrganization(item, organizationId)) continue;
        const id = stringValue(item.id);
        const index = id ? contactItems.findIndex((candidate) => candidate.id === id) : -1;
        if (index < 0) {
          throw overlayTargetError(source.file, 'contacts', id);
        }
        const overlaidContact = normalizeContact(
          applyOverlayFields(contactItems[index]!, item, source.overlay, source.file, 'contacts'),
          config.publisher.origin,
          organizationId,
        );
        contactItems[index] = filterOrganization
          ? filterOrganizationReferences(overlaidContact, organizationId)
          : overlaidContact;
        overlays.push({
          name: source.overlay.name,
          owner: source.overlay.owner,
          priority: source.overlay.priority,
          module: 'contacts',
          sourceFiles: [source.relativePath],
        });
      }
    }
    if (contactItems.length > 0) contactDocument = { ...contactDocument, contacts: contactItems };
    documents['contact-directory'] = contactDocument;
    sourceMap['contact-directory'] = [
      ...contacts.map((source) => source.relativePath),
      ...(groups.get('contacts') ?? [])
        .filter((source) => source.kind === 'overlay')
        .map((source) => source.relativePath),
    ].sort();
  }
  for (const module of MODULES) {
    if (module.key === 'organization' || module.key === 'contacts') continue;
    const moduleSources = (groups.get(module.key) ?? []).filter(
      (source) => source.kind !== 'overlay',
    );
    const moduleOverlaySources = sortedOverlaySources(groups.get(module.key) ?? []);
    if (moduleSources.length === 0) {
      if (moduleOverlaySources.length > 0) {
        throw overlayTargetError(moduleOverlaySources[0]!.file, module.key, undefined);
      }
      continue;
    }
    const items: JsonObject[] = [];
    const sourceFiles = new Set<string>();
    const itemIds = new Set<string>();
    let sourceEnvelope: JsonObject | undefined;
    for (const source of moduleSources) {
      const value = source.value;
      if (isJsonObject(value) && Array.isArray(value.items)) {
        sourceEnvelope ??= value;
      }
      for (const item of extractItems(value, module)) {
        const normalized = normalizeModuleItem(module, item, config.publisher.origin);
        if (filterOrganization && !itemBelongsToOrganization(normalized, organizationId)) continue;
        const organizationScoped = filterOrganization
          ? filterOrganizationReferences(normalized, organizationId)
          : normalized;
        const id = stringValue(normalized.id);
        if (!id) {
          throw new GeneratorInputError('Every module item needs a stable id.', [
            generatorFinding(
              'EOM_GENERATOR_ID_REQUIRED',
              'A module item has no stable id.',
              source.file,
            ),
          ]);
        }
        if (itemIds.has(id)) {
          throw new GeneratorInputError('Duplicate module item id ' + id + '.', [
            generatorFinding(
              'EOM_GENERATOR_DUPLICATE_ID',
              'Stable IDs must be unique within a module.',
              source.file,
              [id],
            ),
          ]);
        }
        itemIds.add(id);
        items.push(organizationScoped);
        sourceFiles.add(source.relativePath);
      }
    }
    for (const source of moduleOverlaySources) {
      if (!source.overlay) continue;
      for (const item of extractItems(source.value, module)) {
        const id = stringValue(item.id);
        const index = id ? items.findIndex((candidate) => candidate.id === id) : -1;
        if (filterOrganization && !itemBelongsToOrganization(item, organizationId)) continue;
        if (index < 0) throw overlayTargetError(source.file, module.key, id);
        const overlaidItem = normalizeModuleItem(
          module,
          applyOverlayFields(items[index]!, item, source.overlay, source.file, module.key),
          config.publisher.origin,
        );
        items[index] = filterOrganization
          ? filterOrganizationReferences(overlaidItem, organizationId)
          : overlaidItem;
        sourceFiles.add(source.relativePath);
        overlays.push({
          name: source.overlay.name,
          owner: source.overlay.owner,
          priority: source.overlay.priority,
          module: module.key,
          sourceFiles: [source.relativePath],
        });
      }
    }
    items.sort((left, right) => compareStrings(textValue(left.id), textValue(right.id)));
    const document = moduleResource(module, items, config, organizationId, sourceEnvelope);
    documents[module.resourceType] = document;
    sourceMap[module.resourceType] = [...sourceFiles].sort();
  }
  return { documents, sourceMap, organizationId, overlays };
}

function itemBelongsToOrganization(item: JsonObject, organizationId: string): boolean {
  const singularFields = [
    'organization',
    'organizationId',
    'organizationRef',
    'owner',
    'provider',
  ] as const;
  const collectionFields = ['organizations', 'organizationsServed'] as const;
  let declaredReference = false;
  let matchedReference = false;
  for (const field of singularFields) {
    const value = item[field];
    const references = Array.isArray(value) ? value : [value];
    for (const reference of references) {
      const id = organizationReferenceId(reference);
      if (id === undefined) continue;
      declaredReference = true;
      // A singular organization/provider binding cannot point at another
      // organization in a filtered publication, even when a separate
      // multi-valued relationship happens to include the selected one.
      if (id !== organizationId) return false;
      matchedReference = true;
    }
  }
  for (const field of collectionFields) {
    const value = item[field];
    if (!Array.isArray(value)) continue;
    const references = value
      .map(organizationReferenceId)
      .filter((id): id is string => id !== undefined);
    if (references.length === 0) continue;
    declaredReference = true;
    if (!references.includes(organizationId)) return false;
    matchedReference = true;
  }
  return !declaredReference || matchedReference;
}

function organizationReferenceId(value: unknown): string | undefined {
  return typeof value === 'string'
    ? value
    : isJsonObject(value)
      ? stringValue(value.id)
      : undefined;
}

/**
 * Remove cross-organization references from a selected organization publication.
 * The item-selection check happens separately so a shared item can remain in the
 * selected publication while its multi-valued organization references are scoped
 * to the selected organization only.
 */
function filterOrganizationReferences(item: JsonObject, organizationId: string): JsonObject {
  const filtered: Record<string, unknown> = { ...item };
  for (const field of [
    'organizations',
    'organizationsServed',
    'partnerOrganizations',
    'dualCreditPartners',
  ] as const) {
    const value = filtered[field];
    if (!Array.isArray(value)) continue;
    filtered[field] = value.filter(
      (reference) => organizationReferenceId(reference) === organizationId,
    );
  }
  return asJsonObject(filtered, 'organization-scoped module item');
}

function applyOverlayFields(
  target: JsonObject,
  patch: JsonObject,
  overlay: EomSourceOverlayConfig,
  sourceFile: string,
  module: string,
): JsonObject {
  const targetId = stringValue(target.id);
  const patchId = stringValue(patch.id);
  if (!targetId || !patchId || targetId !== patchId) {
    throw overlayTargetError(sourceFile, module, patchId);
  }
  const merged: Record<string, unknown> = { ...target };
  for (const [key, value] of Object.entries(patch)) {
    if (key === 'id') continue;
    if (key === '$schema' || key === 'type') {
      throw new GeneratorInputError('Overlay identity fields are immutable.', [
        generatorFinding(
          'EOM_GENERATOR_OVERLAY_IDENTITY',
          'Overlays may not replace an item type or stable id.',
          `${sourceFile}#/${escapeJsonPointer(key)}`,
        ),
      ]);
    }
    const pointer = `/${escapeJsonPointer(key)}`;
    const allowed = overlay.allowedPointers.some(
      (candidate) => pointer === candidate || pointer.startsWith(`${candidate}/`),
    );
    if (!allowed) {
      throw new GeneratorInputError('Overlay field is not allowlisted.', [
        generatorFinding(
          'EOM_GENERATOR_OVERLAY_FIELD_BLOCKED',
          `The overlay ${overlay.name} may not write ${pointer}.`,
          `${sourceFile}#${pointer}`,
        ),
      ]);
    }
    merged[key] = value;
  }
  return asJsonObject(merged, `overlay ${overlay.name}`);
}

function sortedOverlaySources(sources: readonly ParsedSource[]): readonly ParsedSource[] {
  return sources
    .filter((source) => source.kind === 'overlay' && source.overlay !== undefined)
    .sort(
      (left, right) =>
        (left.overlay?.priority ?? 0) - (right.overlay?.priority ?? 0) ||
        compareStrings(left.overlay?.name ?? '', right.overlay?.name ?? '') ||
        compareStrings(left.relativePath, right.relativePath),
    );
}

function overlayTargetError(
  sourceFile: string,
  module: string,
  id: string | undefined,
): GeneratorInputError {
  return new GeneratorInputError('An overlay target was not found in the base publication.', [
    generatorFinding(
      'EOM_GENERATOR_OVERLAY_TARGET',
      `Overlay ${sourceFile} does not match an existing ${module} item${id ? ` ${id}` : ''}.`,
      sourceFile,
    ),
  ]);
}

function escapeJsonPointer(value: string): string {
  return value.replace(/~/gu, '~0').replace(/\//gu, '~1');
}

function duplicateOrganizationError(
  organizationId: string,
  sourceFiles: readonly string[],
): GeneratorInputError {
  return new GeneratorInputError('The selected organization is declared more than once.', [
    generatorFinding(
      'EOM_GENERATOR_DUPLICATE_ORGANIZATION',
      'A selected organization id must occur in only one authoring record.',
      organizationId,
      sourceFiles,
    ),
  ]);
}

function buildContactDocument(
  sources: readonly ParsedSource[],
  organizationId: string,
  config: EomConfig,
): JsonObject {
  const contacts: JsonObject[] = [];
  const ids = new Set<string>();
  for (const source of sources) {
    for (const item of extractItems(source.value, {
      key: 'contacts',
      aliases: [],
      resourceType: 'contact-directory',
      fileName: 'contacts.json',
    })) {
      const normalized = normalizeContact(item, config.publisher.origin, organizationId);
      const id = stringValue(normalized.id);
      if (!id) {
        throw new GeneratorInputError('Every contact needs a stable id.', [
          generatorFinding('EOM_GENERATOR_ID_REQUIRED', 'A contact has no stable id.', source.file),
        ]);
      }
      if (ids.has(id)) {
        throw new GeneratorInputError('Duplicate contact id ' + id + '.', [
          generatorFinding(
            'EOM_GENERATOR_DUPLICATE_ID',
            'Stable IDs must be unique in the contact directory.',
            source.file,
            [id],
          ),
        ]);
      }
      ids.add(id);
      contacts.push(normalized);
    }
  }
  contacts.sort((left, right) => compareStrings(textValue(left.id), textValue(right.id)));
  const document: Record<string, unknown> = {
    $schema: 'https://paperandslate.org/schemas/eom/1.0/contact-directory.schema.json',
    specification: SPECIFICATION,
    version: '1.0',
    id: config.publisher.origin + '/eom/resource/contacts',
    type: 'contact-directory',
    canonical: config.publisher.origin + '/eom/contacts.json',
    subject: organizationId,
    defaultLanguage: config.project.defaultLanguage,
    contacts,
  };
  addPublicationDates(document, config);
  return asJsonObject(document, 'contact directory');
}

function extractItems(value: unknown, module: ModuleDefinition): readonly JsonObject[] {
  if (Array.isArray(value)) {
    return value.filter(isJsonObject);
  }
  if (!isJsonObject(value)) return [];
  if (Array.isArray(value.items)) {
    return value.items.filter(isJsonObject);
  }
  if (module.key === 'contacts' && Array.isArray(value.contacts)) {
    return value.contacts.filter(isJsonObject);
  }
  if (module.key === 'organization' && Array.isArray(value.organizations)) {
    return value.organizations.filter(isJsonObject);
  }
  return [value];
}

function normalizeOrganization(value: unknown, config: EomConfig): JsonObject {
  if (!isJsonObject(value)) {
    throw new GeneratorInputError('Organization source must be an object.', [
      generatorFinding(
        'EOM_GENERATOR_ORGANIZATION_OBJECT',
        'Organization source must be an object.',
      ),
    ]);
  }
  const source = { ...value };
  const sourceType = stringValue(source.type);
  const organizationType =
    stringValue(source.organizationType) ??
    sourceType ??
    config.publisher.organizationType ??
    'organization';
  const id = stringValue(source.id) ?? config.publisher.organizationId;
  const canonical =
    stringValue(source.canonical) ??
    stringValue(source.canonicalUrl) ??
    config.publisher.origin + '/eom/organization.json';
  const document: Record<string, unknown> = {
    $schema: 'https://paperandslate.org/schemas/eom/1.0/organization-profile.schema.json',
    specification: SPECIFICATION,
    version: '1.0',
    id,
    type: 'organization-profile',
    canonical,
    name: source.name ?? config.publisher.organizationName ?? config.project.name,
    organizationType,
  };
  copyIfPresent(source, document, [
    'alternateNames',
    'description',
    'website',
    'identifiers',
    'address',
    'status',
    'founded',
    'defaultLanguage',
    'supportedLanguages',
    'provenance',
    'extensions',
  ]);
  if (source.canonicalUrl && !document.website) document.website = source.canonicalUrl;
  const parent = source.parent ?? source.governingOrganization;
  if (parent) document.parent = toEntityRef(parent);
  for (const key of ['children', 'contacts', 'campuses', 'departments']) {
    if (Array.isArray(source[key])) {
      document[key] = source[key].map(toEntityRef);
    }
  }
  const languages = isJsonObject(source.languages) ? source.languages : undefined;
  if (!document.defaultLanguage && languages && typeof languages.default === 'string') {
    document.defaultLanguage = languages.default;
  }
  if (!document.supportedLanguages && languages && Array.isArray(languages.supported)) {
    document.supportedLanguages = languages.supported;
  }
  addPublicationDates(document, config);
  return asJsonObject(document, 'organization profile');
}

function normalizeContact(value: JsonObject, origin: string, organizationId: string): JsonObject {
  const source = { ...value };
  const document: Record<string, unknown> = { ...source };
  document.id =
    stringValue(source.id) ??
    origin + '/id/contact/' + slugify(source.role ?? source.name ?? 'contact');
  document.type = 'contact-point';
  if (!document.role && source.name) document.role = source.name;
  delete document.name;
  for (const key of ['organization', 'department', 'person']) {
    if (document[key]) document[key] = toEntityRef(document[key]);
  }
  if (!document.organization) document.organization = { id: organizationId };
  return asJsonObject(document, 'contact');
}

function normalizeModuleItem(
  module: ModuleDefinition,
  value: JsonObject,
  origin: string,
): JsonObject {
  const source: Record<string, unknown> = { ...value };
  const aliases: Record<string, string> = {
    timezone: 'timeZone',
    workLocation: 'location',
    closesAt: 'closingAt',
    processUrl: 'applicationUrl',
  };
  for (const [from, to] of Object.entries(aliases)) {
    if (source[to] === undefined && source[from] !== undefined) source[to] = source[from];
    if (from !== to) delete source[from];
  }
  if (module.key === 'news' && source.articleUrl === undefined && source.url !== undefined) {
    source.articleUrl = source.url;
    delete source.url;
  }
  if (module.key === 'policies' && source.documentUrl === undefined && source.url !== undefined) {
    source.documentUrl = source.url;
    delete source.url;
  }
  if (module.key === 'jobs' && source.name === undefined && source.title !== undefined) {
    source.name = source.title;
    delete source.title;
  }
  if (module.key === 'admissions' && source.name === undefined && source.title !== undefined) {
    source.name = source.title;
    delete source.title;
  }
  if (module.key === 'news' && source.headline === undefined && source.title !== undefined) {
    source.headline = source.title;
    delete source.title;
  }
  if (module.key === 'policies' && source.name === undefined && source.title !== undefined) {
    source.name = source.title;
    delete source.title;
  }
  source.type = module.itemType ?? source.type;
  if (!source.id) {
    source.id =
      origin +
      '/id/' +
      module.key +
      '/' +
      slugify(source.code ?? source.name ?? source.title ?? module.key);
  }
  const referenceKeys = new Set([
    'provider',
    'organization',
    'department',
    'parentOrganization',
    'parentDepartment',
    'operator',
    'campus',
    'location',
    'contact',
    'advisor',
    'sport',
    'course',
    'academicPeriod',
    'operatingCalendar',
    'support',
    'organizationRef',
    'publicContact',
    'qualification',
    'replaces',
    'replacedBy',
  ]);
  const referenceArrays = new Set([
    'departments',
    'courses',
    'programs',
    'campuses',
    'organizations',
    'organizationsServed',
    'routes',
    'coaches',
    'homeFacilities',
    'instructors',
    'sections',
    'locations',
    'qualifications',
    'relatedCourses',
    'publicCourses',
    'teams',
    'subjects',
    'corequisites',
    'certifications',
    'dualCreditPartners',
    'nextCourses',
    'equivalentCourses',
    'partnerOrganizations',
  ]);
  for (const key of referenceKeys) {
    if (source[key] !== undefined) source[key] = toEntityRef(source[key]);
  }
  for (const key of referenceArrays) {
    if (Array.isArray(source[key])) source[key] = source[key].map(toEntityRef);
  }
  if (module.key === 'courses' && source.credits && !Array.isArray(source.credits)) {
    source.credits = [source.credits];
  }
  if (module.key === 'courses' && source.provider === undefined) {
    throw new GeneratorInputError('A course source must declare provider.', [
      generatorFinding('EOM_GENERATOR_COURSE_PROVIDER', 'Course provider is required.'),
    ]);
  }
  if (module.key === 'offerings' && source.course === undefined) {
    throw new GeneratorInputError('An offering source must reference a course.', [
      generatorFinding('EOM_GENERATOR_OFFERING_COURSE', 'Course offering references are required.'),
    ]);
  }
  if (module.key === 'calendar' && source.academicYear === undefined && source.year !== undefined) {
    source.academicYear = source.year;
    delete source.year;
  }
  return asJsonObject(source, module.key + ' item');
}

function moduleResource(
  module: ModuleDefinition,
  items: readonly JsonObject[],
  config: EomConfig,
  organizationId: string,
  sourceEnvelope?: JsonObject,
): JsonObject {
  const document: Record<string, unknown> = {
    $schema:
      'https://paperandslate.org/schemas/eom/1.0/modules/' + module.resourceType + '.schema.json',
    specification: SPECIFICATION,
    version: '1.0',
    id: config.publisher.origin + '/eom/resource/' + module.key,
    type: module.resourceType,
    canonical: config.publisher.origin + '/eom/' + module.fileName,
    subjects: [organizationId],
    items,
  };
  if (sourceEnvelope) {
    copyIfPresent(sourceEnvelope, document, [
      'title',
      'description',
      'defaultLanguage',
      'supportedLanguages',
      'license',
      'effective',
      'catalogVersion',
      'releaseStatus',
      'provenance',
      'extensions',
    ]);
  }
  addPublicationDates(document, config);
  return asJsonObject(document, module.key + ' resource');
}

function buildManifest(
  config: EomConfig,
  documents: Readonly<Record<string, JsonObject>>,
  organizationId: string,
  signing?: {
    readonly keySet: string;
    readonly signatures: readonly string[];
    readonly required: boolean;
    readonly algorithm: string;
  },
): JsonObject {
  const organization = documents['organization-profile'];
  const organizationName =
    organization?.name ?? config.publisher.organizationName ?? config.project.name;
  const organizationType =
    stringValue(organization?.organizationType) ??
    config.publisher.organizationType ??
    'organization';
  const profileHref =
    stringValue(organization?.canonical) ?? config.publisher.origin + '/eom/organization.json';
  const resourceEntries = Object.entries(documents)
    .map(([type, document]) => {
      const shortName = shortNameForResource(type);
      const descriptor: Record<string, unknown> = {
        id: config.publisher.origin + '/eom/resource/' + shortName,
        type,
        href:
          stringValue(document.canonical) ??
          config.publisher.origin + '/eom/' + fileNameForResource(type),
        mediaType: 'application/json',
        version: '1.0',
        subjects: [organizationId],
      };
      if (document.modified) descriptor.modified = document.modified;
      if (document.expires) descriptor.expires = document.expires;
      if (document.defaultLanguage) descriptor.languages = [document.defaultLanguage];
      return descriptor;
    })
    .sort((left, right) => compareStrings(String(left.id), String(right.id)));
  const capabilities = resourceEntries.map((resource) => ({
    id: SPECIFICATION + '/capabilities/' + String(resource.type),
    version: '1.0',
    status: 'active',
    resources: [resource.id],
  }));
  const contactDocument = documents['contact-directory'];
  const contactItems =
    contactDocument && Array.isArray(contactDocument.contacts) ? contactDocument.contacts : [];
  const root: Record<string, unknown> = {
    $schema: MANIFEST_SCHEMA,
    specification: SPECIFICATION,
    version: '1.0',
    id:
      config.publisher.origin +
      (config.publisher.manifestPath || '/.well-known/educational-organization-manifest'),
    type: 'manifest',
    canonical:
      config.publisher.origin +
      (config.publisher.manifestPath || '/.well-known/educational-organization-manifest'),
    publisher: {
      id: config.publisher.organizationId ?? organizationId,
      name: organizationName,
      type: organizationType,
      website: config.publisher.origin + '/',
    },
    scope: {
      origin: config.publisher.origin,
      paths: ['/'],
      canonicalOrigins: [config.publisher.origin],
      scopeStatement: 'Public EOM resources for ' + textValue(organizationName) + '.',
    },
    organizations: [
      {
        id: organizationId,
        type: organizationType,
        name: organizationName,
        canonicalUrl: stringValue(organization?.website) ?? profileHref,
        profile: profileHref,
      },
    ],
    defaultLanguage: config.project.defaultLanguage,
    supportedLanguages: config.project.supportedLanguages ?? [config.project.defaultLanguage],
    capabilities,
    resources: resourceEntries,
  };
  if (contactItems.length > 0) {
    root.contacts = contactItems.filter(isJsonObject).map((item) => ({ id: textValue(item.id) }));
  }
  if (config.publication?.notice) {
    root.notices = [
      {
        id: config.publisher.origin + '/id/notice/publication',
        title: 'Publication notice',
        message: config.publication.notice,
      },
    ];
  }
  if (config.publication?.indexingPolicy) {
    root.indexingPolicy = config.publication.indexingPolicy;
  }
  if (signing) root.signing = signing;
  addPublicationDates(root, config);
  return asJsonObject(root, 'manifest');
}

async function createSigningDocuments(
  config: EomConfig,
  configDirectory: string,
  sourceRoot: string,
  documents: Readonly<Record<string, JsonObject>>,
  organizationId: string,
  now: Date,
): Promise<{ readonly keySet: JsonObject; readonly signature: DetachedSignatureRecord }> {
  const keyFile = config.signing?.keyFile;
  const keyId = config.signing?.keyId;
  const organization = documents['organization-profile'];
  if (!keyFile || !keyId || !organization) {
    throw new GeneratorInputError('Signing requires a keyFile, keyId, and organization resource.', [
      generatorFinding(
        'EOM_GENERATOR_SIGNING_CONFIG',
        'Enabled generator signing needs keyFile, keyId, and an organization resource.',
      ),
    ]);
  }
  const keyPath = resolve(configDirectory, keyFile);
  try {
    const keyRealPath = await realpath(keyPath);
    const sourceRealPath = await realpath(sourceRoot);
    if (isWithin(sourceRealPath, keyRealPath)) {
      throw new GeneratorInputError(
        'The signing private key must not be stored below the authoring source root.',
        [
          generatorFinding(
            'EOM_GENERATOR_SIGNING_KEY_UNSAFE',
            'Keep private signing keys outside the source tree and generated publication.',
            keyFile,
          ),
        ],
      );
    }
    const privateKey = createPrivateKey(await readFile(keyRealPath, 'utf8'));
    const publicKey = createPublicKey(privateKey);
    const keySet = asJsonObject(
      {
        $schema: 'https://paperandslate.org/schemas/eom/1.0/key-set.schema.json',
        specification: SPECIFICATION,
        version: '1.0',
        id: config.publisher.origin + '/eom/keys',
        type: 'key-set',
        canonical: config.publisher.origin + '/eom/keys.json',
        keys: [
          publicKeyRecord(publicKey, {
            keyId,
            owner: organizationId,
            purpose: 'EOM publication integrity',
          }),
        ],
      },
      'signing key set',
    );
    addPublicationDates(keySet, config);
    const subject = stringValue(organization.id);
    if (!subject) {
      throw new GeneratorInputError('The organization resource must have an id before signing.', [
        generatorFinding(
          'EOM_GENERATOR_SIGNING_SUBJECT',
          'The organization resource has no stable id for signature binding.',
        ),
      ]);
    }
    const signature = signDetached(organization, {
      privateKey,
      keyId,
      subject,
      canonical: `${subject}#signature`,
      createdAt: now,
    });
    return { keySet, signature };
  } catch (error) {
    if (error instanceof GeneratorInputError) throw error;
    throw new GeneratorInputError('The configured signing key could not be used.', [
      generatorFinding(
        'EOM_GENERATOR_SIGNING_FAILED',
        error instanceof Error ? error.message : 'The configured signing key could not be used.',
        keyFile,
      ),
    ]);
  }
}

function validateAndLint(
  documents: Readonly<Record<string, JsonObject>>,
  config: EomConfig,
  now: Date,
): readonly Finding[] {
  const findings: Finding[] = [];
  for (const [name, document] of Object.entries(documents)) {
    const result = validateDocument(document, { now });
    findings.push(...result.findings.map((item) => ({ ...item, resource: name })));
    if (config.validation?.privacyLint !== false) {
      findings.push(
        ...lintPublication(document, { now }).map((item) => ({ ...item, resource: name })),
      );
    }
  }
  findings.push(
    ...publicationSetFindings(documents, { now }).map((item) => ({
      ...item,
      resource: item.resource ?? 'publication-set',
    })),
  );
  return findings;
}

function isBuildValid(findings: readonly Finding[], config: EomConfig): boolean {
  const failOn = new Set(config.validation?.failOn ?? ['error']);
  return !findings.some((item) => item.severity === 'error' || failOn.has(item.severity));
}

function privacyReport(config: EomConfig, findings: readonly Finding[]): BuildReport['privacy'] {
  const privacyFindings = findings.filter(
    (item) => item.category === 'privacy' || item.category === 'security',
  );
  return {
    status: privacyFindings.some((item) => item.severity === 'error') ? 'blocked' : 'clear',
    acknowledgements: [...(config.validation?.privacyAcknowledgements ?? [])].sort(compareStrings),
    findingCodes: [...new Set(privacyFindings.map((item) => item.code))].sort(compareStrings),
  };
}

function conflictIds(findings: readonly Finding[]): readonly string[] {
  return findings
    .filter((item) => item.code.includes('CONFLICT') || item.code.includes('DUPLICATE_ID'))
    .map((item) => item.resource ?? item.pointer ?? item.code)
    .filter((value, index, values) => values.indexOf(value) === index)
    .sort(compareStrings);
}

async function writePublication(
  outputRoot: string,
  root: JsonObject,
  documents: Readonly<Record<string, JsonObject>>,
  config: EomConfig,
  report: BuildReport,
  prettyPrint: boolean,
  mode: BuildMode,
): Promise<string> {
  const parent = dirname(outputRoot);
  await mkdir(parent, { recursive: true });
  const temporary = await mkdtemp(join(parent, '.eom-public-'));
  const publisherOrigin = isJsonObject(root.scope) ? stringValue(root.scope.origin) : undefined;
  try {
    const wellKnown = join(temporary, '.well-known');
    const eom = join(temporary, 'eom');
    await mkdir(wellKnown, { recursive: true });
    await mkdir(eom, { recursive: true });
    await writeJson(
      join(temporary, GENERATED_MARKER),
      generatedMarker(config, report, mode, publisherOrigin, root),
      true,
    );
    await writeJson(join(wellKnown, 'educational-organization-manifest'), root, prettyPrint);
    await writeJson(join(wellKnown, 'educational-organization-manifest.json'), root, prettyPrint);
    for (const [type, document] of Object.entries(documents)) {
      await writeJson(join(eom, fileNameForResource(type)), document, prettyPrint);
    }
    const publicFiles = await walkFiles(temporary);
    const outputEntries: JsonObject[] = [];
    for (const file of publicFiles) {
      outputEntries.push({
        path: normalizePath(relative(temporary, file)),
        sha256: await sha256File(file),
      });
    }
    outputEntries.sort((left, right) =>
      compareStrings(textValue(left.path), textValue(right.path)),
    );
    const fingerprint = sha256Text(jsonText(outputEntries, true));
    const buildDirectory = buildDirectoryForOutput(outputRoot, mode);
    const buildTemporary = await mkdtemp(join(parent, '.eom-build-'));
    try {
      await writeJson(
        join(buildTemporary, 'input-manifest.json'),
        {
          toolVersion: report.toolVersion,
          specification: report.specification,
          configDigest: report.configDigest,
          files: report.inputs.map((input) => ({
            path: input.relativePath,
            module: input.module,
            sha256: input.sha256,
          })),
        },
        true,
      );
      await writeJson(
        join(buildTemporary, GENERATED_MARKER),
        generatedMarker(config, report, mode, publisherOrigin, root),
        true,
      );
      await writeJson(
        join(buildTemporary, 'output-manifest.json'),
        {
          toolVersion: report.toolVersion,
          specification: report.specification,
          configDigest: report.configDigest,
          files: outputEntries,
          fingerprint,
        },
        true,
      );
      await writeJson(
        join(buildTemporary, 'validation.json'),
        {
          valid: report.valid,
          findings: report.findings,
        },
        true,
      );
      await writeJson(
        join(buildTemporary, 'lint.json'),
        {
          findings: report.findings.filter(
            (item) =>
              item.category === 'privacy' ||
              item.category === 'quality' ||
              item.category === 'security' ||
              item.category === 'freshness',
          ),
        },
        true,
      );
      await writeJson(join(buildTemporary, 'source-map.json'), report.sourceMap, true);
      await writeJson(
        join(buildTemporary, 'reproducibility.json'),
        {
          deterministic: true,
          canonicalJson: true,
          fingerprint,
          inputFingerprint: sha256Text(
            jsonText(
              report.inputs.map((input) => ({
                path: input.relativePath,
                module: input.module,
                sha256: input.sha256,
              })),
              true,
            ),
          ),
        },
        true,
      );
      await writeJson(
        join(buildTemporary, 'build-report.json'),
        {
          toolVersion: report.toolVersion,
          specification: report.specification,
          configDigest: report.configDigest,
          valid: report.valid,
          mode: report.mode,
          ...(report.partial ? { partial: report.partial } : {}),
          inputs: report.inputs.map((input) => ({
            path: input.relativePath,
            module: input.module,
            sha256: input.sha256,
          })),
          resources: report.resources,
          overlays: report.overlays,
          privacy: report.privacy,
          conflicts: report.conflicts,
          findings: report.findings,
          fingerprint,
        },
        true,
      );
      await replacePublicationPair(temporary, outputRoot, buildTemporary, buildDirectory, {
        buildMode: mode,
        projectIdentity: projectIdentity(config),
        selector: selectorForReport(report, mode),
      });
    } catch (error) {
      await rm(buildTemporary, { recursive: true, force: true });
      throw error;
    }
    return fingerprint;
  } catch (error) {
    await rm(temporary, { recursive: true, force: true });
    throw error;
  }
}

async function replacePublicationPair(
  publicationTemporary: string,
  publicationTarget: string,
  buildTemporary: string,
  buildTarget: string,
  expected: ReplacementMarkerExpectation,
): Promise<void> {
  const parent = dirname(publicationTarget);
  if (dirname(buildTarget) !== parent) {
    throw unsafeOutputError(
      buildTarget,
      'Publication and build-report directories must share a protected parent for atomic replacement.',
    );
  }
  // Keep the parent identity stable for the entire replacement window. The
  // lock also prevents concurrent generator processes from interleaving their
  // marker checks and renames. A stale lock fails closed and is safe to remove
  // only after confirming no generator process is still running.
  await assertNoSymlinkEscape(parent);
  const expectedParent = await realpath(parent);
  const lockPath = join(parent, '.eom-replace.lock');
  let lockAcquired = false;
  try {
    await mkdir(lockPath);
    await writeFile(
      join(lockPath, 'owner.json'),
      JSON.stringify({ generator: 'eom', pid: process.pid, startedAt: new Date().toISOString() }),
      'utf8',
    );
    lockAcquired = true;
  } catch (error) {
    if (isAlreadyExists(error)) {
      const ownerPath = join(lockPath, 'owner.json');
      try {
        const owner = parseStrictJson(await readFile(ownerPath, 'utf8'), ownerPath);
        const pid = isJsonObject(owner) && typeof owner.pid === 'number' ? owner.pid : undefined;
        if (pid !== undefined && Number.isInteger(pid) && !isProcessAlive(pid)) {
          const lockInformation = await lstat(lockPath);
          if (!lockInformation.isDirectory() || lockInformation.isSymbolicLink()) {
            throw unsafeOutputError(parent, 'The generator replacement lock is not a directory.');
          }
          await rm(lockPath, { recursive: true, force: true });
          await mkdir(lockPath);
          await writeFile(
            ownerPath,
            JSON.stringify({
              generator: 'eom',
              pid: process.pid,
              startedAt: new Date().toISOString(),
            }),
            'utf8',
          );
          lockAcquired = true;
        }
      } catch (ownerError) {
        if (ownerError instanceof GeneratorInputError) throw ownerError;
        // An unreadable or incomplete lock is intentionally fail-closed. It may
        // belong to a process that has not finished writing its owner record.
      }
    }
    if (lockAcquired) {
      // A stale lock was safely replaced after its owner process was confirmed dead.
    } else {
      throw unsafeOutputError(
        parent,
        error instanceof Error && 'code' in error && error.code === 'EEXIST'
          ? 'Another generator replacement is already in progress.'
          : 'The generator could not acquire an exclusive replacement lock.',
      );
    }
  }
  if (!lockAcquired) {
    throw unsafeOutputError(
      parent,
      'The generator could not acquire an exclusive replacement lock.',
    );
  }
  try {
    await recoverPendingReplacementTransactions(parent, expectedParent);
  } catch (error) {
    await rm(lockPath, { recursive: true, force: true }).catch(() => undefined);
    throw error;
  }
  let transaction: string | undefined;
  let movedPublication = false;
  let movedBuild = false;
  let installedPublication = false;
  let installedBuild = false;
  let preserveTransaction = false;
  try {
    await assertStableReplacementParent(parent, expectedParent);
    // Validate both targets immediately before moving either one. This keeps a
    // build report and its publication as one ownership-checked transaction.
    const publicationIdentity = await directoryIdentity(publicationTarget, publicationTarget);
    const buildIdentity = await directoryIdentity(buildTarget, buildTarget);
    await assertReplaceableDirectory(publicationTarget, publicationTarget, expected);
    await assertReplaceableDirectory(buildTarget, buildTarget, expected);
    transaction = await mkdtemp(join(parent, '.eom-replace-'));
    const publicationBackup = join(transaction, 'publication.previous');
    const buildBackup = join(transaction, 'build.previous');
    let journal: ReplacementJournal = {
      version: 1,
      status: 'prepared',
      publicationTarget: relative(parent, publicationTarget),
      buildTarget: relative(parent, buildTarget),
      publicationBackup: 'publication.previous',
      buildBackup: 'build.previous',
      expected,
    };
    await writeReplacementJournal(transaction, journal);
    try {
      await assertStableReplacementParent(parent, expectedParent);
      await assertDirectoryIdentity(publicationTarget, publicationIdentity, publicationTarget);
      await rename(publicationTarget, publicationBackup);
      await assertMovedDirectoryIdentity(publicationBackup, publicationIdentity, publicationTarget);
      movedPublication = true;
      journal = { ...journal, status: 'publication-moved' };
      await writeReplacementJournal(transaction, journal);
    } catch (error) {
      if (!isNotFound(error) || publicationIdentity !== undefined) throw error;
    }
    try {
      await assertStableReplacementParent(parent, expectedParent);
      await assertDirectoryIdentity(buildTarget, buildIdentity, buildTarget);
      await rename(buildTarget, buildBackup);
      await assertMovedDirectoryIdentity(buildBackup, buildIdentity, buildTarget);
      movedBuild = true;
      journal = { ...journal, status: 'build-moved' };
      await writeReplacementJournal(transaction, journal);
    } catch (error) {
      if (!isNotFound(error) || buildIdentity !== undefined) throw error;
    }
    await assertStableReplacementParent(parent, expectedParent);
    await rename(buildTemporary, buildTarget);
    installedBuild = true;
    journal = { ...journal, status: 'build-installed' };
    await writeReplacementJournal(transaction, journal);
    await assertStableReplacementParent(parent, expectedParent);
    await rename(publicationTemporary, publicationTarget);
    installedPublication = true;
    journal = { ...journal, status: 'publication-installed' };
    await writeReplacementJournal(transaction, journal);
    await assertStableReplacementParent(parent, expectedParent);
    journal = { ...journal, status: 'committed' };
    await writeReplacementJournal(transaction, journal);
    await rm(transaction, { recursive: true, force: true });
  } catch (error) {
    if (error instanceof ReplacementIntegrityError) preserveTransaction = true;
    if (
      transaction &&
      !preserveTransaction &&
      (await isStableReplacementParent(parent, expectedParent))
    ) {
      const publicationBackup = join(transaction, 'publication.previous');
      const buildBackup = join(transaction, 'build.previous');
      if (installedPublication) {
        await rm(publicationTarget, { recursive: true, force: true }).catch(() => undefined);
      }
      if (installedBuild) {
        await rm(buildTarget, { recursive: true, force: true }).catch(() => undefined);
      }
      if (movedBuild) {
        await rename(buildBackup, buildTarget).catch(() => undefined);
      }
      if (movedPublication) {
        await rename(publicationBackup, publicationTarget).catch(() => undefined);
      }
      await rm(transaction, { recursive: true, force: true }).catch(() => undefined);
    }
    throw error;
  } finally {
    if (lockAcquired && (await isStableReplacementParent(parent, expectedParent))) {
      await rm(lockPath, { recursive: true, force: true }).catch(() => undefined);
    }
  }
}

async function writeReplacementJournal(
  transaction: string,
  journal: ReplacementJournal,
): Promise<void> {
  const journalPath = join(transaction, 'journal.json');
  const temporary = join(transaction, 'journal.tmp');
  await writeFile(temporary, jsonText(journal, true), 'utf8');
  await rename(temporary, journalPath);
}

async function recoverPendingReplacementTransactions(
  parent: string,
  expectedParent: string,
): Promise<void> {
  await assertStableReplacementParent(parent, expectedParent);
  const entries = await readdir(parent, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.name.startsWith('.eom-replace-')) continue;
    if (!entry.isDirectory() || entry.isSymbolicLink()) {
      throw unsafeOutputError(
        join(parent, entry.name),
        'An interrupted generator transaction must be a real directory.',
      );
    }
    const transaction = join(parent, entry.name);
    const journal = await readReplacementJournal(transaction);
    const publicationTarget = resolveJournalPath(parent, journal.publicationTarget, 'publication');
    const buildTarget = resolveJournalPath(parent, journal.buildTarget, 'build');
    if (dirname(publicationTarget) !== parent || dirname(buildTarget) !== parent) {
      throw unsafeOutputError(
        transaction,
        'An interrupted generator transaction references a target outside its protected parent.',
      );
    }
    const publicationBackup = join(transaction, journal.publicationBackup);
    const buildBackup = join(transaction, journal.buildBackup);
    const expected = journal.expected;
    if (journal.status === 'committed') {
      if (
        (await directoryIdentity(publicationTarget, publicationTarget)) === undefined ||
        (await directoryIdentity(buildTarget, buildTarget)) === undefined
      ) {
        throw unsafeOutputError(
          transaction,
          'A committed generator transaction is missing one of its output directories.',
        );
      }
      await assertReplaceableDirectory(publicationTarget, publicationTarget, expected);
      await assertReplaceableDirectory(buildTarget, buildTarget, expected);
      await assertReplaceableDirectory(publicationBackup, publicationBackup, expected);
      await assertReplaceableDirectory(buildBackup, buildBackup, expected);
      await rm(transaction, { recursive: true, force: true });
      continue;
    }
    await rollbackPendingTarget(publicationTarget, publicationBackup, expected, false);
    await rollbackPendingTarget(
      buildTarget,
      buildBackup,
      expected,
      journal.status === 'build-installed' || journal.status === 'publication-installed',
    );
    await rm(transaction, { recursive: true, force: true });
  }
}

async function readReplacementJournal(transaction: string): Promise<ReplacementJournal> {
  const journalPath = join(transaction, 'journal.json');
  let value: JsonValue;
  try {
    value = parseStrictJson(await readFile(journalPath, 'utf8'), journalPath);
  } catch {
    throw unsafeOutputError(
      transaction,
      'An interrupted generator transaction is missing a valid recovery journal.',
    );
  }
  if (!isJsonObject(value)) {
    throw unsafeOutputError(transaction, 'The generator recovery journal must be an object.');
  }
  const statuses: readonly ReplacementJournalStatus[] = [
    'prepared',
    'publication-moved',
    'build-moved',
    'build-installed',
    'publication-installed',
    'committed',
  ];
  const expected = value.expected;
  if (
    value.version !== 1 ||
    typeof value.status !== 'string' ||
    !statuses.includes(value.status as ReplacementJournalStatus) ||
    typeof value.publicationTarget !== 'string' ||
    typeof value.buildTarget !== 'string' ||
    value.publicationBackup !== 'publication.previous' ||
    value.buildBackup !== 'build.previous' ||
    !isJsonObject(expected) ||
    typeof expected.buildMode !== 'string' ||
    !['full', 'module', 'organization', 'changed-files'].includes(expected.buildMode) ||
    typeof expected.projectIdentity !== 'string' ||
    !isJsonObject(expected.selector)
  ) {
    throw unsafeOutputError(transaction, 'The generator recovery journal is invalid.');
  }
  return {
    version: 1,
    status: value.status as ReplacementJournalStatus,
    publicationTarget: value.publicationTarget,
    buildTarget: value.buildTarget,
    publicationBackup: value.publicationBackup,
    buildBackup: value.buildBackup,
    expected: {
      buildMode: expected.buildMode as BuildMode,
      projectIdentity: expected.projectIdentity,
      selector: expected.selector,
    },
  };
}

function resolveJournalPath(parent: string, value: string, label: string): string {
  const resolved = resolve(parent, value);
  if (
    !value ||
    isAbsolute(value) ||
    !isWithin(parent, resolved) ||
    normalizePath(relative(parent, resolved)) !== normalizePath(value)
  ) {
    throw unsafeOutputError(
      join(parent, value),
      `The generator recovery journal ${label} target is outside its protected parent.`,
    );
  }
  return resolved;
}

async function rollbackPendingTarget(
  target: string,
  backup: string,
  expected: ReplacementMarkerExpectation,
  removeUnbackedTarget: boolean,
): Promise<void> {
  const backupIdentity = await directoryIdentity(backup, backup);
  const targetIdentity = await directoryIdentity(target, target);
  if (backupIdentity !== undefined) {
    await assertReplaceableDirectory(backup, backup, expected);
    if (targetIdentity !== undefined) {
      await assertReplaceableDirectory(target, target, expected);
      await rm(target, { recursive: true, force: true });
    }
    await rename(backup, target);
    await assertMovedDirectoryIdentity(target, backupIdentity, target);
    return;
  }
  if (removeUnbackedTarget && targetIdentity !== undefined) {
    await assertReplaceableDirectory(target, target, expected);
    await rm(target, { recursive: true, force: true });
  }
}

async function assertStableReplacementParent(
  parent: string,
  expectedRealPath: string,
): Promise<void> {
  await assertNoSymlinkEscape(parent);
  if (normalizeFsPath(await realpath(parent)) !== normalizeFsPath(expectedRealPath)) {
    throw unsafeOutputError(
      parent,
      'The generator replacement parent changed during the atomic publication transaction.',
    );
  }
}

async function isStableReplacementParent(
  parent: string,
  expectedRealPath: string,
): Promise<boolean> {
  try {
    return normalizeFsPath(await realpath(parent)) === normalizeFsPath(expectedRealPath);
  } catch {
    return false;
  }
}

async function writeJson(path: string, value: unknown, prettyPrint: boolean): Promise<void> {
  await writeFile(path, jsonText(value, prettyPrint), 'utf8');
}

function addPublicationDates(document: Record<string, unknown>, config: EomConfig): void {
  if (config.publication?.modified) document.modified = config.publication.modified;
  if (config.publication?.expires) document.expires = config.publication.expires;
}

function copyIfPresent(
  source: Record<string, unknown>,
  target: Record<string, unknown>,
  keys: readonly string[],
): void {
  for (const key of keys) {
    if (source[key] !== undefined) target[key] = source[key];
  }
}

function toEntityRef(value: unknown): JsonObject {
  if (typeof value === 'string') return { id: value };
  if (!isJsonObject(value)) return { id: String(value) };
  const reference: Record<string, unknown> = { id: value.id };
  for (const key of ['type', 'name']) {
    if (value[key] !== undefined) reference[key] = value[key];
  }
  return asJsonObject(reference, 'entity reference');
}

function itemCount(document: JsonObject): number {
  if (Array.isArray(document.items)) return document.items.length;
  if (Array.isArray(document.contacts)) return document.contacts.length;
  return 1;
}

function shortNameForResource(type: string): string {
  if (type === 'organization-profile') return 'organization';
  if (type === 'contact-directory') return 'contacts';
  return moduleDefinition(type)?.key ?? type.replace(/-catalog$/u, '');
}

function fileNameForResource(type: string): string {
  if (type === 'organization-profile') return 'organization.json';
  if (type === 'contact-directory') return 'contacts.json';
  if (type === 'key-set') return 'keys.json';
  if (type === 'signature') return 'signature.json';
  return moduleDefinition(type)?.fileName ?? type + '.json';
}

function normalizeKey(value: string): string {
  return value.replace(/[-_\\s]/gu, '').toLowerCase();
}

function normalizePath(value: string): string {
  return value.split(sep).join('/');
}

function slugify(value: unknown): string {
  const slug = String(value)
    .normalize('NFKD')
    .replace(/[^\p{Letter}\p{Number}]+/gu, '-')
    .replace(/^-+|-+$/gu, '')
    .toLowerCase();
  return slug || 'item';
}

function stringValue(value: unknown): string | undefined {
  return typeof value === 'string' && value.length > 0 ? value : undefined;
}

function textValue(value: unknown): string {
  if (typeof value === 'string') return value;
  if (value === null || value === undefined) return '';
  if (typeof value === 'number' || typeof value === 'boolean' || typeof value === 'bigint') {
    return `${value}`;
  }
  return JSON.stringify(value) ?? Object.prototype.toString.call(value);
}

function asJsonObject(value: unknown, label: string): JsonObject {
  assertJsonSafe(value, label, 0);
  if (!isJsonObject(value)) throw new GeneratorInputError(label + ' must be an object.');
  return value;
}

function assertJsonSafe(value: unknown, source: string, depth: number): asserts value is JsonValue {
  if (depth > 64) {
    throw new GeneratorInputError('Authoring nesting exceeds the safety limit.', [
      generatorFinding('EOM_GENERATOR_NESTING_LIMIT', 'Authoring nesting is too deep.', source),
    ]);
  }
  if (
    value === null ||
    typeof value === 'string' ||
    typeof value === 'boolean' ||
    (typeof value === 'number' && Number.isFinite(value))
  ) {
    if (typeof value === 'string' && !isWellFormedUnicode(value)) {
      throw new GeneratorInputError('Authoring input contains invalid Unicode.', [
        generatorFinding(
          'EOM_GENERATOR_UNICODE_INVALID',
          'Unpaired UTF-16 surrogates are not valid publication text.',
          source,
        ),
      ]);
    }
    return;
  }
  if (Array.isArray(value)) {
    for (const item of value) assertJsonSafe(item, source, depth + 1);
    return;
  }
  if (typeof value === 'object') {
    for (const [key, child] of Object.entries(value)) {
      if (!isWellFormedUnicode(key)) {
        throw new GeneratorInputError('Authoring input contains invalid Unicode.', [
          generatorFinding(
            'EOM_GENERATOR_UNICODE_INVALID',
            'Unpaired UTF-16 surrogates are not valid publication text.',
            source + '/' + key,
          ),
        ]);
      }
      assertJsonSafe(child, source + '/' + key, depth + 1);
    }
    return;
  }
  throw new GeneratorInputError('Authoring input contains a non-JSON value.', [
    generatorFinding(
      'EOM_GENERATOR_NON_JSON_VALUE',
      'Only JSON-compatible YAML values are allowed.',
      source,
    ),
  ]);
}

function isWellFormedUnicode(value: string): boolean {
  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index);
    if (code >= 0xd800 && code <= 0xdbff) {
      const next = value.charCodeAt(index + 1);
      if (next >= 0xdc00 && next <= 0xdfff) {
        index += 1;
        continue;
      }
      return false;
    }
    if (code >= 0xdc00 && code <= 0xdfff) return false;
  }
  return true;
}

function jsonText(value: unknown, prettyPrint: boolean): string {
  const jsonValue = stableJsonValue(asJsonValue(value, 'JSON output'));
  return prettyPrint ? stringifyCanonical(jsonValue) : JSON.stringify(jsonValue) + '\n';
}

function asJsonValue(value: unknown, label: string): JsonValue {
  assertJsonSafe(value, label, 0);
  return value;
}

function generatorFinding(
  code: string,
  message: string,
  resource?: string,
  related: readonly string[] = [],
): Finding {
  return {
    code,
    category: code.indexOf('YAML') >= 0 || code.indexOf('INPUT') >= 0 ? 'syntax' : 'quality',
    message,
    severity: 'error',
    ...(resource ? { resource } : {}),
    ...(related.length > 0 ? { related } : {}),
  };
}

function sha256Text(value: string): string {
  return createHash('sha256').update(value, 'utf8').digest('hex');
}

function sha256Bytes(value: Uint8Array): string {
  return createHash('sha256').update(value).digest('hex');
}

async function sha256File(path: string): Promise<string> {
  return createHash('sha256')
    .update(await readFile(path))
    .digest('hex');
}

function compareStrings(left: string, right: string): number {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function escapeRegExp(value: string): string {
  return value.replace(/[\\^$.*+?()[\]{}|]/gu, '\\$&');
}

async function directoryIdentity(
  path: string,
  displayPath: string,
): Promise<DirectoryIdentity | undefined> {
  let information;
  try {
    information = await lstat(path);
  } catch (error) {
    if (isNotFound(error)) return undefined;
    throw error;
  }
  if (!information.isDirectory() || information.isSymbolicLink()) {
    throw unsafeOutputError(displayPath, 'The replacement target must be a real directory.');
  }
  return { device: information.dev, inode: information.ino };
}

async function assertDirectoryIdentity(
  path: string,
  expected: DirectoryIdentity | undefined,
  displayPath: string,
): Promise<void> {
  const actual = await directoryIdentity(path, displayPath);
  if (
    (expected === undefined && actual !== undefined) ||
    (expected !== undefined &&
      (actual === undefined ||
        actual.device !== expected.device ||
        actual.inode !== expected.inode))
  ) {
    throw unsafeOutputError(
      displayPath,
      'The replacement target changed after ownership validation; refusing to move it.',
    );
  }
}

async function assertMovedDirectoryIdentity(
  path: string,
  expected: DirectoryIdentity | undefined,
  displayPath: string,
): Promise<void> {
  try {
    const actual = await directoryIdentity(path, displayPath);
    if (
      expected === undefined ||
      actual === undefined ||
      actual.device !== expected.device ||
      actual.inode !== expected.inode
    ) {
      throw new Error('the moved replacement target identity changed');
    }
  } catch (error) {
    throw new ReplacementIntegrityError(
      displayPath,
      `The replacement target changed during its move; the transaction was preserved for recovery. (${error instanceof Error ? error.message : String(error)})`,
    );
  }
}

function isAlreadyExists(error: unknown): boolean {
  return isNodeError(error) && error.code === 'EEXIST';
}

function isProcessAlive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return isNodeError(error) && error.code !== 'ESRCH';
  }
}

function isNotFound(error: unknown): boolean {
  return isNodeError(error) && error.code === 'ENOENT';
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && 'code' in error;
}
